const BOX = ['###', '###', '###', '###', '###'];

// 5 rows of 3 characters ('#' set, '.' clear). Lower case maps to capitals; unknown characters give a filled box.
export function glyph(ch) {
  const c = typeof ch === 'string' ? ch.toUpperCase() : '';
  return G[c] || G[ch] || BOX;
}

export const textWidth = (text) => (text.length === 0 ? 0 : text.length * ADVANCE - (ADVANCE - GLYPH_W));

// Draws one line with its top-left at (x, y), one fillRect per run of set pixels.
export function drawText(ctx, text, x, y, colour) {
  ctx.fillStyle = colour;
  for (let i = 0; i < text.length; i++) {
    const rows = glyph(text[i]);
    for (let r = 0; r < GLYPH_H; r++) {
      let c = 0;
      while (c < GLYPH_W) {
        if (rows[r][c] !== '#') { c++; continue; }
        let e = c;
        while (e < GLYPH_W && rows[r][e] === '#') e++;
        ctx.fillRect(x + i * ADVANCE + c, y + r, e - c, 1);
        c = e;
      }
    }
  }
}
